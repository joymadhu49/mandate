import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import { generatePrivateKey, privateKeyToAccount } from 'viem/accounts';
import { keccak256, concatHex } from 'viem';
const base='https://mandate.horizonbase.app';
const api=(path,body,token)=>fetch(base+path,{method:body===undefined?'GET':'POST',headers:{accept:'application/json','content-type':'application/json',...(token?{authorization:`Bearer ${token}`}:{})},...(body===undefined?{}:{body:JSON.stringify(body)}),signal:AbortSignal.timeout(45000)});
const health=await api('/');assert.equal(health.status,200);assert.equal(health.headers.get('x-mandate-host'),'cloudflare');assert.equal((await health.json()).dryRun,false);
assert.equal((await api('/mandates')).status,401);
assert.equal((await api('/demo/mandate-build13-demo.mp4')).status,200);
const wallet=privateKeyToAccount(generatePrivateKey());
const challenge=await(await api('/auth/challenge',{account:wallet.address})).json();
assert.ok(challenge.nonce);
const response=await api('/auth/verify',{nonce:challenge.nonce,signature:await wallet.signMessage({message:challenge.message})});
assert.equal(response.status,200,await response.clone().text());
const session=await response.json();
const state=await(await api('/agent',undefined,session.token)).json();
const signingRoot=readFileSync('data/spender.key','utf8').trim();
assert.equal(state.spender.toLowerCase(),privateKeyToAccount(keccak256(concatHex([signingRoot,wallet.address.toLowerCase()]))).address.toLowerCase());
assert.equal(state.ai.configured,true);assert.equal(state.dryRun,false);
assert.equal((await api('/mode',{live:false},session.token)).status,403);
assert.deepEqual(await(await api('/mandates',undefined,session.token)).json(),[]);
writeFileSync('data/cloud-smoke-session.json',JSON.stringify({session,account:wallet.address}),{mode:0o600});
const chat=await api('/chat',{requestId:randomUUID(),message:'Which stocks can I research in this app? Do not propose a trade.'},session.token);
assert.equal(chat.status,200,await chat.clone().text());
const message=await chat.json();assert.ok(message.text);assert.equal(message.proposal,undefined);
writeFileSync('data/cloud-smoke-session.json',JSON.stringify({session,account:wallet.address}),{mode:0o600});
console.log('PASS: public domain served by Cloudflare, live mode preserved, demo available, wallet login, existing signer derivation, account isolation, operator guard, and AI research response. No spending approval or trade performed.');
